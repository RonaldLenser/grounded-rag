"""Claim verification: never trust the model, check its evidence in code.

The model returns claims, each with evidence items (source id + verbatim quote).
For every evidence item:
  1. The source_id must be one we actually sent.      (catches invented sources)
  2. The quote must be long enough to mean something. (catches "the" as a "quote")
  3. The quote must actually appear in that source.   (catches invented quotes)

A claim is SUPPORTED only if it has at least one evidence item and ALL of its
evidence passes. One fabricated quote makes the whole claim untrusted: a model
that invented support for a statement is not reliable on that statement.

The visible answer is then BUILT from supported claims only, with [S#] markers
generated by code from verified evidence. Rejected claims are not edited, they
are dropped: their text never leaves this module (results carry reasons, not
text). That is the guarantee: unsupported text cannot reach the user by having
its bad citation removed.

Status rules:
  - Model refusal               -> insufficient_context, fixed message.
  - No supported claims         -> insufficient_context, fixed message.
  - "answered" + rejected claims -> partial, with a notice that some statements
                                    could not be verified.

Honest limit: this proves each quote EXISTS in its source. It does not prove
the claim faithfully follows from the quote (entailment). That gap is measured
by the groundedness eval (M7).
"""

import html
import re
import unicodedata
from dataclasses import dataclass, field
from typing import Literal

from grounded.generation.prompts import (
    INSUFFICIENT_CONTEXT_MESSAGE,
    AnswerStatus,
    LLMAnswer,
    LLMClaim,
    Source,
)

MIN_QUOTE_CHARS = 12

PARTIAL_COVERAGE_NOTICE = "The documents only partly answer this question."
UNVERIFIED_CLAIMS_NOTICE = (
    "Some statements were left out because they could not be verified against the documents."
)

EvidenceRejection = Literal["unknown_source", "quote_too_short", "quote_not_found"]
ClaimRejection = Literal["empty_text", "no_evidence", "invalid_evidence"]

_MARKER = re.compile(r"\s*\[\s*S\d+\s*\]")
_WHITESPACE = re.compile(r"\s+")
_TRAILING_PUNCTUATION = re.compile(r"[.!?]+$")
_TYPOGRAPHY = str.maketrans({"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-"})


def normalize_for_match(text: str) -> str:
    """Compare text the way a human would: ignore case, spacing, and curly-vs-straight quotes."""
    text = unicodedata.normalize("NFKC", html.unescape(text)).translate(_TYPOGRAPHY)
    return _WHITESPACE.sub(" ", text).casefold().strip()


@dataclass(frozen=True)
class VerifiedEvidence:
    source: Source
    quote: str


@dataclass(frozen=True)
class RejectedEvidence:
    source_id: str
    reason: EvidenceRejection


@dataclass(frozen=True)
class SupportedClaim:
    text: str  # cleaned claim text, without markers
    evidence: tuple[VerifiedEvidence, ...]

    @property
    def source_ids(self) -> list[str]:
        return list(dict.fromkeys(e.source.source_id for e in self.evidence))


@dataclass(frozen=True)
class RejectedClaim:
    """Why a claim was dropped. Deliberately carries NO claim text."""

    reason: ClaimRejection
    evidence: tuple[RejectedEvidence, ...] = ()


@dataclass(frozen=True)
class VerificationResult:
    status: AnswerStatus
    answer: str
    claims: list[SupportedClaim] = field(default_factory=list)
    rejected_claims: list[RejectedClaim] = field(default_factory=list)
    notice: str | None = None
    downgraded_from: AnswerStatus | None = None

    @property
    def verified(self) -> list[VerifiedEvidence]:
        """Evidence behind the displayed claims, deduplicated, in answer order."""
        unique: dict[tuple[str, str], VerifiedEvidence] = {}
        for claim in self.claims:
            for evidence in claim.evidence:
                key = (evidence.source.source_id, normalize_for_match(evidence.quote))
                unique.setdefault(key, evidence)
        return list(unique.values())

    @property
    def rejected_evidence(self) -> list[RejectedEvidence]:
        return [e for claim in self.rejected_claims for e in claim.evidence]


def verify_answer(llm_answer: LLMAnswer, sources: list[Source]) -> VerificationResult:
    if llm_answer.status == "insufficient_context":
        # Trust a refusal, but show our fixed message, not model-written text.
        return VerificationResult(
            status="insufficient_context", answer=INSUFFICIENT_CONTEXT_MESSAGE
        )

    by_id = {source.source_id: source for source in sources}
    supported: list[SupportedClaim] = []
    rejected: list[RejectedClaim] = []
    seen_texts: set[str] = set()

    for llm_claim in llm_answer.claims:
        outcome = _verify_claim(llm_claim, by_id)
        if isinstance(outcome, RejectedClaim):
            rejected.append(outcome)
            continue
        key = normalize_for_match(outcome.text)
        if key not in seen_texts:  # the same claim twice: show it once
            seen_texts.add(key)
            supported.append(outcome)

    if not supported:
        return VerificationResult(
            status="insufficient_context",
            answer=INSUFFICIENT_CONTEXT_MESSAGE,
            rejected_claims=rejected,
            downgraded_from=llm_answer.status,
        )

    status: AnswerStatus = llm_answer.status
    downgraded_from: AnswerStatus | None = None
    if status == "answered" and rejected:
        status, downgraded_from = "partial", "answered"

    notices = []
    if llm_answer.status == "partial":
        notices.append(PARTIAL_COVERAGE_NOTICE)
    if rejected:
        notices.append(UNVERIFIED_CLAIMS_NOTICE)

    return VerificationResult(
        status=status,
        answer=" ".join(_render(claim) for claim in supported),
        claims=supported,
        rejected_claims=rejected,
        notice=" ".join(notices) or None,
        downgraded_from=downgraded_from,
    )


def _verify_claim(claim: LLMClaim, by_id: dict[str, Source]) -> SupportedClaim | RejectedClaim:
    text = _clean_claim_text(claim.text)
    if not text:
        return RejectedClaim("empty_text")
    if not claim.evidence:
        return RejectedClaim("no_evidence")

    verified: list[VerifiedEvidence] = []
    failures: list[RejectedEvidence] = []
    for item in claim.evidence:
        source_id = item.source_id.strip()
        quote = item.quote.strip().strip(".,;:").strip()
        normalized_quote = normalize_for_match(quote)
        source = by_id.get(source_id)
        if source is None:
            failures.append(RejectedEvidence(source_id, "unknown_source"))
        elif len(normalized_quote) < MIN_QUOTE_CHARS:
            failures.append(RejectedEvidence(source_id, "quote_too_short"))
        elif normalized_quote not in normalize_for_match(source.chunk.content):
            failures.append(RejectedEvidence(source_id, "quote_not_found"))
        else:
            verified.append(VerifiedEvidence(source=source, quote=quote))

    if failures:
        return RejectedClaim("invalid_evidence", tuple(failures))
    return SupportedClaim(text=text, evidence=tuple(verified))


def _clean_claim_text(text: str) -> str:
    """Strip any markers the model wrote: only code-generated markers are trusted."""
    return _WHITESPACE.sub(" ", _MARKER.sub("", text)).strip()


def _render(claim: SupportedClaim) -> str:
    """'Leaders are accountable.' + [S1, S3] -> 'Leaders are accountable [S1][S3].'"""
    markers = "".join(f"[{source_id}]" for source_id in claim.source_ids)
    match = _TRAILING_PUNCTUATION.search(claim.text)
    end = match.group(0) if match else "."
    body = claim.text[: match.start()] if match else claim.text
    return f"{body.rstrip()} {markers}{end}"
